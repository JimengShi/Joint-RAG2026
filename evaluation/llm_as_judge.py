"""LLM-as-Judge with multiple judges (GPT-4o, GPT-5.2 and GPT-6.1 by default).

Each judge rates every predicted answer against the gold answer on correctness
and completeness (0 or 1 each). For each judge we compute the average
correctness (%); the reported LLM-as-Judge score is the mean over judges.
Completeness is kept in the saved per-sample file but not reported.

Per-sample judgments are saved to <output>_judged.json. Re-running the script
reuses judgments already in that file, so an interrupted run can be resumed.

Example:
    python evaluation/llm_as_judge.py --data legalbench --model gpt-4o-mini --retrieval_method hypercube --k 5
"""
import argparse
import json
import os
import sys
from concurrent.futures import ThreadPoolExecutor

from openai import OpenAI, BadRequestError
from tqdm import tqdm

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from evaluation.common import add_common_args, resolve_output_path, load_samples

JUDGE_MODELS = {
    "gpt-4o": "gpt-4o-2024-11-20",
    "gpt-5.2": "gpt-5.2-2025-12-11",
    "gpt-6.1": "gpt-6.1-sol",
}
DEFAULT_JUDGES = ["gpt-4o", "gpt-5.2", "gpt-6.1"]

SYSTEM_PROMPT = (
    "You are an expert evaluator on natural sciences, such as hurricanes, geography, and aging dams. Your task is to assess the predicted answer generated by AI models compared to the gold (reference) answer. "
    "Please evaluate the predicted answer on correctness and completeness."
    "For the given question. Evaluate using two criteria:\n\n"
    "1. Correctness (0 or 1):\n"
    "- Score 1 if the predicted answer is generally accurate and aligns with the key points in the reference answer.\n"
    "- Score 0 if it has factual errors or misrepresents key information.\n\n"
    "2. Completeness (0 or 1):\n"
    "- Score 1 if the predicted answer covers the main points present in the reference answer.\n"
    "- Score 0 if it misses essential information or fails to address the core of the question.\n\n"
    "Output your evaluation in the following JSON format:\n"
    '{"correctness": int, "completeness": int, "explanation": "your brief explanation"}'
)

_no_temperature = set()  # judges that reject temperature=0 (e.g., reasoning models)


def _chat(client, judge, messages):
    model_id = JUDGE_MODELS[judge]
    if judge not in _no_temperature:
        try:
            return client.chat.completions.create(model=model_id, messages=messages, temperature=0)
        except BadRequestError as e:
            if "temperature" not in str(e):
                raise
            _no_temperature.add(judge)
    return client.chat.completions.create(model=model_id, messages=messages)


# ================ Evaluate ================
def evaluate_answer(client, judge, question, gold_answer, predicted_answer):
    user_prompt = f"Question: {question}, Gold Answer: {gold_answer}, Predicted Answer: {predicted_answer}, please evaluate the predicted answer based on correctness and completeness."
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_prompt},
    ]
    try:
        reply = _chat(client, judge, messages).choices[0].message.content or ""
    except Exception as e:
        print(f"[{judge}] API error: {e}")
        return {"correctness": -1, "completeness": -1, "explanation": f"API error: {e}"}

    try:
        result = json.loads(reply.strip().removeprefix("```json").removeprefix("```").removesuffix("```").strip())
        result["correctness"] = int(result["correctness"])
        result["completeness"] = int(result.get("completeness", -1))
    except (json.JSONDecodeError, KeyError, TypeError, ValueError):
        print(f"[{judge}] Failed to parse JSON from model output. Raw output:\n", reply)
        result = {"correctness": -1, "completeness": -1, "explanation": "Parse error"}
    return result


# ================ Argument Parser ================
def parse_args():
    parser = argparse.ArgumentParser(description="Judge LLM answers with multiple LLM judges and average their correctness.")
    add_common_args(parser)
    parser.add_argument("--judges", type=str, nargs="+", default=DEFAULT_JUDGES, choices=list(JUDGE_MODELS),
                        help="LLM judges to use (default: gpt-4o gpt-5.2 gpt-6.1).")
    parser.add_argument("--workers", type=int, default=8, help="Number of concurrent API requests.")
    return parser.parse_args()


# ================ Main Function ================
def main():
    args = parse_args()
    path = resolve_output_path(args)
    out_path = path.replace(".json", "_judged.json")

    # Resume from an earlier (possibly interrupted) run if its judgments exist.
    samples = load_samples(out_path if os.path.exists(out_path) else path)
    client = OpenAI()

    # Collect (sample, judge) pairs that still need a valid judgment.
    tasks = []
    for sample in samples:
        judgments = sample.setdefault("judgments", {})
        for judge in args.judges:
            if judgments.get(judge, {}).get("correctness", -1) < 0:
                tasks.append((sample, judge))

    def run(task):
        sample, judge = task
        # NQ/PopQA outputs store a list of accepted answers under "gold_answers";
        # the other datasets store a single string under "gold_answer".
        gold_answer = sample.get("gold_answers", sample.get("gold_answer"))
        sample["judgments"][judge] = evaluate_answer(client, judge, sample["question"], gold_answer, sample["predicted_answer"])

    print(f"{len(tasks)} judgments to run ({len(samples)} samples x {len(args.judges)} judges, others reused).")
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        list(tqdm(pool.map(run, tasks), total=len(tasks)))

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(samples, f, indent=2, ensure_ascii=False)

    # === Scores: average correctness per judge, then mean over judges ===
    n = len(samples)
    print(f"File: {path}")
    per_judge = {}
    for judge in args.judges:
        scores = [s["judgments"][judge]["correctness"] for s in samples]
        errors = sum(1 for c in scores if c < 0)  # parse/API errors count as incorrect
        per_judge[judge] = sum(max(c, 0) for c in scores) / n * 100
        print(f"  {judge:8s} ({JUDGE_MODELS[judge]}): correctness {per_judge[judge]:.1f}, errors: {errors}")
    print(f"Total samples: {n}, LLM-as-Judge (mean correctness over {len(args.judges)} judges): "
          f"{sum(per_judge.values()) / len(per_judge):.1f}")
    print(f"Per-sample judgments saved to {out_path}")


if __name__ == "__main__":
    main()
