"""HippoRAG 2 baseline, run with the official package (pip install hipporag,
https://github.com/OSU-NLP-Group/HippoRAG). Indexing uses NV-Embed-v2 and the
chosen LLM; answers are generated by HippoRAG's own QA step from the top-k
retrieved passages, as in the HippoRAG 2 paper.

For --model llama3, HippoRAG calls the LLM through an OpenAI-compatible API
(Together AI by default), and reads its key from OPENAI_API_KEY, so set
OPENAI_API_KEY to your Together key for that run.

Example:
    python baselines/qa_rag_hipporag2.py --data legalbench --model gpt-4o-mini --k 5
"""
import os
import sys

from tqdm import tqdm

sys.path.append(os.path.dirname(os.path.abspath(__file__)))

from common import LLMS, parse_args, read_corpus, load_qa, make_record
from utils.metric import em_check, f1_score

TOGETHER_BASE_URL = "https://api.together.xyz/v1"


def main():
    parser = parse_args("HippoRAG 2 baseline.")
    parser.add_argument("--llm_base_url", type=str, default=None,
                        help="OpenAI-compatible endpoint for the LLM (default: Together AI for llama3, OpenAI otherwise).")
    args = parser.parse_args()

    from hipporag import HippoRAG

    provider, model_id = LLMS[args.model]
    base_url = args.llm_base_url or (TOGETHER_BASE_URL if provider == "together" else None)

    corpus = read_corpus(args.data)
    hipporag = HippoRAG(
        save_dir=f"cache/hipporag2_{args.data}_{args.model}",
        llm_model_name=model_id,
        llm_base_url=base_url,
        embedding_model_name="nvidia/NV-Embed-v2",
    )
    hipporag.index(docs=corpus)

    # map passage text -> first line id in the corpus file
    line_id = {}
    for i, doc in enumerate(corpus):
        line_id.setdefault(doc, i)

    qa_samples = load_qa(args.data)
    if args.limit:
        qa_samples = qa_samples[:args.limit]

    outputs, total_em, total_f1 = [], 0.0, 0.0
    for i, sample in enumerate(tqdm(qa_samples)):
        question = sample["question"]
        retrieval = hipporag.retrieve(queries=[question], num_to_retrieve=args.k)
        doc_ids = [line_id.get(d, -1) for d in retrieval[0].docs[:args.k]]
        predicted_answer = hipporag.rag_qa(retrieval)[0][0].answer

        record = make_record(args.data, i + 1, question, sample, predicted_answer, doc_ids)
        golds = record["gold_answers"] if isinstance(record["gold_answers"], list) else [record["gold_answer"]]
        total_em += em_check(predicted_answer, golds)
        total_f1 += max(f1_score(g, predicted_answer) for g in golds)
        outputs.append(record)

    n = len(qa_samples)
    print(f"[hipporag2] {args.data} / {args.model}: {n} samples, EM {total_em / n * 100:.1f}, F1 {total_f1 / n * 100:.1f}")

    if args.save == "true":
        import json
        output_dir = f"output/{args.data}/{args.model}"
        os.makedirs(output_dir, exist_ok=True)
        path = f"{output_dir}/llm_output_hipporag2_k{args.k}_responses.json"
        with open(path, "w", encoding="utf-8") as f:
            json.dump(outputs, f, indent=2, ensure_ascii=False)
        print(f"Saved to {path}")


if __name__ == "__main__":
    main()
